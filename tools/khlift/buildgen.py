#!/usr/bin/env python3
"""buildgen.py --root DIR : write build manifests next to DIR/shards.json.
   DIR/build.x86.ninja    gcc, x86-64 Linux (differential oracle build)
   DIR/build.arm64.ninja  clang, arm64 (Apple clang / macOS or iOS SDK, selected by $SDK)
   DIR/Makefile           arm64 / x86 make build for hosts without ninja (make ARCH=arm64|x86 [SHARDS="0000 0001"])
   DIR/CMakeLists.txt     generic CMake project (object library of all shards + runtime)
 Layout expected under DIR: shards/*.c  gen/{kh_table,rt_imports_default,nep_stubs}.c  rt/*  (rt = tools/rt copy)
 The lifted code is compiled with the flags that implement POLICY.md: -ffp-contract=off -fno-math-errno -fwrapv
 -fno-strict-aliasing -fno-delete-null-pointer-checks, no -ffast-math, no -ffinite-math-only."""
import sys, os, json, argparse
FLAGS = '-O1 -w -fno-strict-aliasing -fwrapv -fno-delete-null-pointer-checks -fno-math-errno -ffp-contract=off -I rt -I gen'
RTSRC = ['rt/khrt_cpu.c', 'rt/khrt_rcp_tab.c', 'rt/khrt_dispatch.c', 'rt/rt_libm.c', 'gen/kh_table.c', 'gen/rt_imports_default.c', 'gen/nep_stubs.c']

def ninja(root, shards, name, cc, extra, objdir):
    L = ['# generated by tools/buildgen.py', 'cc = %s' % cc, 'cflags = %s %s' % (FLAGS, extra),
         'wrap = python3 tools/ccwrap.py logs/compile_%s.jsonl' % objdir,
         'rule cc', '  command = $wrap $out $cc $cflags -c $in -o $out', '  description = CC $out',
         'rule ar', '  command = rm -f $out && ar rcs $out $in', '']
    objs = []
    for s in shards:
        o = 'obj/%s/%s.o' % (objdir, s['name'][:-2]); objs.append(o)
        L.append('build %s: cc shards/%s' % (o, s['name']))
    rt = []
    for src in RTSRC:
        o = 'obj/%s/%s.o' % (objdir, os.path.basename(src)[:-2]); rt.append(o); L.append('build %s: cc %s' % (o, src))
    L += ['build lib/%s/libkh2rt.a: ar %s' % (objdir, ' '.join(rt)),
          'build lib/%s/libkh2lifted.a: ar %s' % (objdir, ' '.join(objs)),
          'build runtime: phony lib/%s/libkh2rt.a' % objdir, 'build all: phony lib/%s/libkh2lifted.a lib/%s/libkh2rt.a' % (objdir, objdir), 'default runtime']
    open(os.path.join(root, name), 'w').write('\n'.join(L) + '\n')

def makefile(root, shards):
    L = ['# generated by tools/buildgen.py   usage: make ARCH=arm64 [J=2] SHARDS="0000 0001" ; make ARCH=arm64 all',
         'ARCH ?= arm64', 'ifeq ($(ARCH),arm64)', 'CC ?= clang', 'ARCHFLAGS = -arch arm64', 'else', 'CC ?= gcc', 'ARCHFLAGS =', 'endif',
         'CFLAGS = %s $(ARCHFLAGS) $(EXTRA)' % FLAGS, 'OBJ = obj/$(ARCH)', 'LIB = lib/$(ARCH)',
         'WRAP = python3 tools/ccwrap.py logs/compile_$(ARCH).jsonl', '',
         '$(OBJ)/%.o: shards/%.c', '\t@mkdir -p $(OBJ)', '\t$(WRAP) $@ $(CC) $(CFLAGS) -c $< -o $@',
         '$(OBJ)/%.o: rt/%.c', '\t@mkdir -p $(OBJ)', '\t$(WRAP) $@ $(CC) $(CFLAGS) -c $< -o $@',
         '$(OBJ)/%.o: gen/%.c', '\t@mkdir -p $(OBJ)', '\t$(WRAP) $@ $(CC) $(CFLAGS) -c $< -o $@', '']
    L.append('RTOBJ = ' + ' '.join('$(OBJ)/%s.o' % os.path.basename(s)[:-2] for s in RTSRC))
    L.append('SHARDOBJ = ' + ' '.join('$(OBJ)/%s.o' % s['name'][:-2] for s in shards))
    L += ['runtime: $(RTOBJ)', '\t@mkdir -p $(LIB) && rm -f $(LIB)/libkh2rt.a && ar rcs $(LIB)/libkh2rt.a $(RTOBJ)',
          'all: runtime $(SHARDOBJ)', '\t@mkdir -p $(LIB) && rm -f $(LIB)/libkh2lifted.a && ar rcs $(LIB)/libkh2lifted.a $(SHARDOBJ)',
          'sel: $(foreach s,$(SHARDS),$(OBJ)/shard_$(s).o)', '.PHONY: runtime all sel']
    open(os.path.join(root, 'Makefile'), 'w').write('\n'.join(L) + '\n')

def cmake(root, shards):
    L = ['# generated by tools/buildgen.py', 'cmake_minimum_required(VERSION 3.16)', 'project(kh2lifted C)',
         'set(CMAKE_C_FLAGS "${CMAKE_C_FLAGS} %s")' % FLAGS.replace('-I rt -I gen', '-I${CMAKE_SOURCE_DIR}/rt -I${CMAKE_SOURCE_DIR}/gen'),
         'set(CMAKE_C_FLAGS_RELEASE "")', 'set(CMAKE_BUILD_TYPE Release)',
         'option(KH_XLATE_MODE "0 identity, 1 const bias, 2 dynamic bias" 0)', 'add_compile_definitions(KH_XLATE_MODE=${KH_XLATE_MODE})',
         'add_library(kh2rt STATIC ' + ' '.join(RTSRC) + ')',
         'add_library(kh2lifted STATIC', *['  shards/%s' % s['name'] for s in shards], ')', 'target_link_libraries(kh2lifted PUBLIC kh2rt)']
    open(os.path.join(root, 'CMakeLists.txt'), 'w').write('\n'.join(L) + '\n')

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--root', required=True); a = ap.parse_args()
    shards = json.load(open(os.path.join(a.root, 'shards.json')))['shards']
    ninja(a.root, shards, 'build.x86.ninja', 'gcc', '', 'x86')
    ninja(a.root, shards, 'build.arm64.ninja', 'clang', '-arch arm64', 'arm64')
    makefile(a.root, shards); cmake(a.root, shards)
    print('wrote manifests for %d shards' % len(shards))

if __name__ == '__main__':
    main()
