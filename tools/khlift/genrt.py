#!/usr/bin/env python3
"""Generate the runtime glue that depends on the universe: dispatch table, import table, weak import defaults, .nep stubs.
  genrt.py --out DIR     -> DIR/kh_table.c DIR/rt_imports_default.c DIR/nep_stubs.c DIR/khrt_imports.h
"""
import sys, os, argparse
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from khlift import BASE, universe as U, imports as IM
import lift_all as LA

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--out', required=True); a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    fs = U.load(); hooks = LA.load_hooks(); imps = IM.load_imports()
    # kh_table.c
    lines = ['/* generated by tools/genrt.py from scratch/universe/functions (game-derived addresses: never commit) */', '#include "khrt_tables.h"']
    syms = {}
    for f in fs:
        syms[f.rva] = hooks.get(f.va, 'f_%x' % f.rva)
    for rva in sorted(syms): lines.append('void %s(KCtx *g);' % syms[rva])
    for im in imps: lines.append('void %s(KCtx *g);' % im.sym)
    lines.append('const KhFnEnt kh_fn_table[] = {')
    for rva in sorted(syms): lines.append(' {0x%x,%s},' % (rva, syms[rva]))
    lines.append('};\nconst u32 kh_fn_count = %d;' % len(syms))
    lines.append('const KhImportEnt kh_import_table[] = {')
    for im in imps:
        lines.append(' {0x%x,%s,"%s","%s"},' % (im.slot - BASE, im.sym, im.dll, im.name or ('#%d' % im.ordinal)))
    lines.append('};\nconst u32 kh_import_count = %d;' % len(imps))
    open(os.path.join(a.out, 'kh_table.c'), 'w').write('\n'.join(lines) + '\n')
    # weak defaults
    w = ['/* weak default for every import and hook: aborts with the name.  The real runtime provides strong definitions. */',
         '#include "khrt_tables.h"']
    for im in imps:
        w.append('__attribute__((weak)) void %s(KCtx *g){ kh_unimplemented_import(g,"%s","%s"); }' % (im.sym, im.dll, im.name or '#%d' % im.ordinal))
    for va, sym in sorted(hooks.items()):
        w.append('__attribute__((weak)) void %s(KCtx *g){ kh_unimplemented_import(g,"hook","%s"); }' % (sym, sym))
    open(os.path.join(a.out, 'rt_imports_default.c'), 'w').write('\n'.join(w) + '\n')
    # nep stubs
    n = ['/* .nep CLR native-entry units: meaningless off Windows, abort if reached */', '#include "khrt_tables.h"']
    for f in fs:
        if f.nep: n.append('void f_%x(KCtx *g){ kh_nep_stub(g,0x%x); }' % (f.rva, f.rva))
    open(os.path.join(a.out, 'nep_stubs.c'), 'w').write('\n'.join(n) + '\n')
    # header
    h = ['/* khrt_imports.h : every import of kh2fm.exe as a named runtime function (guest ABI void f(KCtx*)), generated. */',
         '#pragma once', '#include "khrt.h"']
    for im in imps:
        h.append('void %s(KCtx *g);   /* %s!%s  IAT slot rva 0x%x */' % (im.sym, im.dll, im.name or '#%d' % im.ordinal, im.slot - BASE))
    for va, sym in sorted(hooks.items()): h.append('void %s(KCtx *g);   /* hook for guest 0x%x */' % (sym, va))
    open(os.path.join(a.out, 'khrt_imports.h'), 'w').write('\n'.join(h) + '\n')
    print('kh_table: %d functions, %d imports, %d nep stubs, %d hooks' % (len(syms), len(imps), sum(1 for f in fs if f.nep), len(hooks)))

if __name__ == '__main__':
    main()
