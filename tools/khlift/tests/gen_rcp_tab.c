/* gen_rcp_tab.c : measure this CPU's RCPPS / RSQRTPS and write rt/khrt_rcp_tab.c (x86-64 host with SSE only).
 *   cc -O2 -msse4.1 gen_rcp_tab.c -o gen_rcp_tab && ./gen_rcp_tab > ../rt/khrt_rcp_tab.c
 * RCPPS and RSQRTPS results depend only on sign, exponent and the top 12 mantissa bits (verified exhaustively for all 2^32
 * inputs by rcp_model_check.c).  The table stores the full hardware result at one reference exponent per class:
 *   rcp : x in [1,2)   (e=127)        rsqrt even : x in [2,4) (e=128)     rsqrt odd : x in [1,2) (e=127). */
#include <stdio.h>
#include <stdint.h>
#include <immintrin.h>
static uint32_t hw_rcp(uint32_t x){ return _mm_cvtsi128_si32(_mm_castps_si128(_mm_rcp_ps(_mm_castsi128_ps(_mm_set1_epi32(x))))); }
static uint32_t hw_rsq(uint32_t x){ return _mm_cvtsi128_si32(_mm_castps_si128(_mm_rsqrt_ps(_mm_castsi128_ps(_mm_set1_epi32(x))))); }
int main(void){
    printf("/* generated by tools/tests/gen_rcp_tab.c on the CPU whose RCPPS/RSQRTPS this reproduces (POLICY.md section 5). */\n#include \"khrt.h\"\n");
    printf("const u32 kh_rcp_tab[3*4096] = {\n");
    for(int k=0;k<3;k++){ for(int t=0;t<4096;t++){
        uint32_t r = k==0 ? hw_rcp(0x3f800000u|(t<<11)) : k==1 ? hw_rsq(0x40000000u|(t<<11)) : hw_rsq(0x3f800000u|(t<<11));
        printf("0x%08x,%s",r,(t&7)==7?"\n":""); } }
    printf("};\n"); return 0; }
